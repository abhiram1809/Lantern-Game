const W = 2048, H = 1024;
const px = (lon, lat) => [((lon + 180) / 360) * W, ((90 - lat) / 180) * H];

let cached = null;

// { land, lights }: CanvasTextures (equirectangular, longitude -180 at u = 0).
export function earthMaps() {
  if (cached) return cached;
  const land = document.createElement('canvas');
  land.width = W; land.height = H;
  const g = land.getContext('2d');
  g.fillStyle = '#000';
  g.fillRect(0, 0, W, H);
  const fill = (polys, color) => {
    g.fillStyle = color;
    for (const poly of polys) {
      g.beginPath();
      poly.forEach(([lon, lat], i) => { const [x, y] = px(lon, lat); if (i) g.lineTo(x, y); else g.moveTo(x, y); });
      g.closePath();
      g.fill();
    }
  };
  fill(LAND, '#fff');
  // Antarctica: a ragged band round the pole, with the peninsula reaching toward South America
  g.beginPath();
  g.moveTo(0, H);
  for (let lon = -180; lon <= 180; lon += 5) {
    const lat = -70 + 2.4 * Math.sin(lon * 0.09) + 1.6 * Math.sin(lon * 0.23 + 1) + (lon > 150 || lon < -150 ? -6 : 0) + (lon > -80 && lon < -40 ? -4 : 0);
    const [x, y] = px(lon, lat);
    g.lineTo(x, y);
  }
  g.lineTo(W, H);
  g.fill();
  fill([[[-57, -63.3], [-62, -64.5], [-66, -67], [-68, -70], [-63, -70], [-60, -66]]], '#fff');
  fill(WATER, '#000');

  // night lights: soft glows over each cluster, then thousands of town specks scattered round them
  const lights = document.createElement('canvas');
  lights.width = W; lights.height = H;
  const l = lights.getContext('2d');
  l.fillStyle = '#000';
  l.fillRect(0, 0, W, H);
  l.globalCompositeOperation = 'lighter';
  let seed = 7;
  const rnd = () => ((seed = (seed * 16807) % 2147483647) - 1) / 2147483646;
  // a density map: a glow over each cluster and smaller ones scattered round it (towns, roads);
  // the planet shader turns density into individual specks of light
  const blob = (x, y, r, a) => {
    const grad = l.createRadialGradient(x, y, 0, x, y, r);
    grad.addColorStop(0, `rgba(255,255,255,${a})`);
    grad.addColorStop(0.4, `rgba(255,255,255,${a * 0.35})`);
    grad.addColorStop(1, 'rgba(255,255,255,0)');
    l.fillStyle = grad;
    l.fillRect(x - r, y - r, r * 2, r * 2);
  };
  for (const [lon, lat, s, spread] of CITIES) {
    const [x, y] = px(lon, lat), r = (spread / 360) * W * 1.6;
    blob(x, y, r, 0.6 * s);
    for (let i = 0; i < 26 * s + 6; i++) {
      const a = rnd() * Math.PI * 2, d = Math.pow(rnd(), 0.6) * r * 3;
      blob(x + Math.cos(a) * d, y + Math.sin(a) * d * 0.8, r * (0.12 + rnd() * 0.25), 0.2 + rnd() * 0.35 * s);
    }
  }
  l.globalCompositeOperation = 'source-over';
  const tex = (c) => {
    const t = new THREE.CanvasTexture(c);
    t.colorSpace = THREE.NoColorSpace;
    t.wrapS = THREE.RepeatWrapping;
    t.anisotropy = 8;
    return t;
  };
  cached = { land: tex(land), lights: tex(lights), landCanvas: land };
  return cached;
}
